import { describe, expect, test } from "bun:test";
import { generateConfig, type RunOptions } from "./singbox";

const serverConf = `[Interface]
PrivateKey = FAKE_PRIVATE_KEY
Address = 10.0.0.2/32, fc00::2/128
DNS = 10.0.0.1, fc00::1
MTU = 1420

[Peer]
PublicKey = FAKE_PUBLIC_KEY
PresharedKey = FAKE_PRESHARED_KEY
AllowedIPs = 0.0.0.0/0, ::/0
Endpoint = vpn.example.com:51820
PersistentKeepalive = 25
`;

const base: Omit<RunOptions, "serverFile"> = {
  socksPort: 25344,
  mode: "split",
  domains: [
    { id: "a", value: "reddit.com", kind: "domain", enabled: true },
    { id: "b", value: "medium.com", kind: "domain", enabled: false },
  ],
};

function config(overrides: Partial<typeof base> = {}, conf = serverConf) {
  const raw = generateConfig(conf, { ...base, ...overrides });
  return JSON.parse(raw.replace(/^\/\/.*\n/, ""));
}

describe("generateConfig", () => {
  test("marks the generated config as auto-generated", () => {
    const raw = generateConfig(serverConf, base);
    expect(raw.startsWith("// auto-generated by patchbay")).toBe(true);
  });

  test("maps the wireguard conf to a userspace endpoint", () => {
    const endpoint = config().endpoints[0];
    expect(endpoint.type).toBe("wireguard");
    expect(endpoint.tag).toBe("tunnel");
    expect(endpoint.address).toEqual(["10.0.0.2/32", "fc00::2/128"]);
    expect(endpoint.private_key).toBe("FAKE_PRIVATE_KEY");
    expect(endpoint.mtu).toBe(1420);
    expect(endpoint.domain_resolver).toBe("dns-direct");
    expect(endpoint.peers[0]).toEqual({
      address: "vpn.example.com",
      port: 51820,
      public_key: "FAKE_PUBLIC_KEY",
      pre_shared_key: "FAKE_PRESHARED_KEY",
      allowed_ips: ["0.0.0.0/0", "::/0"],
      persistent_keepalive_interval: 25,
    });
  });

  test("listens on the configured socks port", () => {
    const generated = config();
    expect(generated.inbounds[0]).toMatchObject({
      type: "socks",
      listen: "127.0.0.1",
      listen_port: 25344,
    });
  });

  test("routes enabled domains through the tunnel and skips disabled ones", () => {
    const generated = config();
    expect(generated.route.rules).toEqual([
      {
        domain: ["reddit.com"],
        domain_suffix: [".reddit.com"],
        action: "route",
        outbound: "tunnel",
      },
    ]);
    expect(generated.route.final).toBe("direct");
  });

  test("keeps regex rules as domain_regex", () => {
    const generated = config({
      domains: [{ id: "r", value: "^.*\\.example\\.com$", kind: "regex", enabled: true }],
    });
    expect(generated.route.rules[0].domain_regex).toEqual(["^.*\\.example\\.com$"]);
  });

  test("resolves tunneled domains through the tunnel dns", () => {
    const generated = config();
    expect(generated.dns.servers).toContainEqual({
      type: "udp",
      tag: "dns-tunnel",
      server: "10.0.0.1",
      detour: "tunnel",
    });
    expect(generated.dns.rules).toEqual([
      { domain: ["reddit.com"], domain_suffix: [".reddit.com"], server: "dns-tunnel" },
    ]);
    expect(generated.dns.final).toBe("dns-direct");
    expect(generated.route.default_domain_resolver).toBe("dns-direct");
  });

  test("empty split rules tunnel nothing", () => {
    const generated = config({ domains: [] });
    expect(generated.route.rules).toEqual([]);
    expect(generated.route.final).toBe("direct");
  });

  test("full mode sends everything through the tunnel", () => {
    const generated = config({ mode: "full" });
    expect(generated.route.rules).toEqual([]);
    expect(generated.route.final).toBe("tunnel");
    expect(generated.route.default_domain_resolver).toBe("dns-direct");
    expect(generated.dns.rules).toEqual([]);
    expect(generated.dns.final).toBe("dns-tunnel");
    expect(generated.endpoints[0].domain_resolver).toBe("dns-direct");
  });

  test("merges repeated address and dns lines", () => {
    const generated = config(
      {},
      `[Interface]
PrivateKey = FAKE_PRIVATE_KEY
Address = 10.0.0.2/32
Address = 10.0.0.3/32, fc00::2/128
DNS = 10.0.0.1
DNS = 10.0.0.9

[Peer]
PublicKey = FAKE_PUBLIC_KEY
AllowedIPs = 0.0.0.0/0
Endpoint = vpn.example.com:51820
`,
    );
    expect(generated.endpoints[0].address).toEqual([
      "10.0.0.2/32",
      "10.0.0.3/32",
      "fc00::2/128",
    ]);
    expect(generated.dns.servers[1].server).toBe("10.0.0.1");
  });

  test("rejects a config without interface or peer fields", () => {
    expect(() => generateConfig("[Interface]\nPrivateKey = x\n", base)).toThrow();
  });
});
