use std::path::Path;

use anyhow::Context as _;
use serde::Serialize;
use serde_json::{Map, Value, json};

use super::openvpn::{self, OpenVpnConfig};
use super::wireguard::{self, WireguardConfig, WireguardPeer};
use crate::config::Mode;
use crate::domains::{DomainRule, RuleKind};
use crate::engine::EngineOptions;
use crate::json::to_pretty_json;
use crate::servers::Protocol;

const TUNNEL_TAG: &str = "tunnel";
const DIRECT_TAG: &str = "direct";

const HEADER: &str = "// auto-generated by patchbay; edits will be overwritten\n";

pub fn generate_config(
    protocol: Protocol,
    server_conf: &str,
    profile: &Path,
    options: &EngineOptions,
) -> anyhow::Result<String> {
    let (dns, endpoint) = match protocol {
        Protocol::Wireguard => {
            let config = wireguard::parse(server_conf)
                .with_context(|| format!("parsing {}", profile.display()))?;
            let dns = config.dns.first().cloned();
            (dns, Endpoint::Wireguard(wireguard_endpoint(config)))
        }
        Protocol::OpenVpn => {
            let config = openvpn::parse(server_conf, profile)
                .with_context(|| format!("parsing {}", profile.display()))?;
            let dns = config.dns.first().cloned();
            (dns, Endpoint::OpenVpn(Box::new(openvpn_endpoint(config))))
        }
    };
    let split = options.mode == Mode::Split;
    let fields = if split {
        match_fields(&options.domains)
    } else {
        Map::new()
    };

    let mut dns_rules = Vec::new();
    let mut route_rules = Vec::new();
    if !fields.is_empty() {
        let mut dns_rule = fields.clone();
        dns_rule.insert("server".to_string(), json!("dns-tunnel"));
        dns_rules.push(Value::Object(dns_rule));

        let mut route_rule = fields;
        route_rule.insert("action".to_string(), json!("route"));
        route_rule.insert("outbound".to_string(), json!(TUNNEL_TAG));
        route_rules.push(Value::Object(route_rule));
    }

    let tunnel_dns = dns.unwrap_or_else(|| "1.1.1.1".to_string());

    let config = GeneratedConfig {
        log: LogConfig {
            level: "info",
            timestamp: true,
        },
        dns: DnsConfig {
            servers: vec![
                json!({ "type": "local", "tag": "dns-direct" }),
                json!({
                    "type": "udp",
                    "tag": "dns-tunnel",
                    "server": tunnel_dns,
                    "detour": TUNNEL_TAG,
                }),
            ],
            rules: dns_rules,
            final_server: if split { "dns-direct" } else { "dns-tunnel" }.to_string(),
        },
        inbounds: vec![Inbound {
            type_: "socks",
            tag: "socks-in",
            listen: "127.0.0.1",
            listen_port: options.socks_port,
        }],
        endpoints: vec![endpoint],
        outbounds: vec![Outbound {
            type_: "direct",
            tag: DIRECT_TAG,
        }],
        route: RouteConfig {
            rules: route_rules,
            final_outbound: if split { DIRECT_TAG } else { TUNNEL_TAG }.to_string(),
            default_domain_resolver: "dns-direct",
        },
    };

    let mut output = String::from(HEADER);
    output.push_str(&to_pretty_json(&config)?);
    Ok(output)
}

fn wireguard_endpoint(config: WireguardConfig) -> WireguardEndpoint {
    WireguardEndpoint {
        type_: "wireguard",
        tag: TUNNEL_TAG,
        domain_resolver: "dns-direct",
        address: config.addresses,
        private_key: config.private_key,
        peers: config.peers.into_iter().map(Peer::from).collect(),
        mtu: config.mtu,
    }
}

fn openvpn_endpoint(config: OpenVpnConfig) -> OpenVpnEndpoint {
    OpenVpnEndpoint {
        type_: "openvpn-client",
        tag: TUNNEL_TAG,
        domain_resolver: "dns-direct",
        mode: "tls",
        config,
        route_no_pull: true,
    }
}

fn match_fields(rules: &[DomainRule]) -> Map<String, Value> {
    let mut fields = Map::new();
    for rule in rules.iter().filter(|rule| rule.enabled) {
        match rule.kind {
            RuleKind::Domain => {
                push_entry(&mut fields, "domain", &rule.value);
                push_entry(&mut fields, "domain_suffix", &format!(".{}", rule.value));
            }
            RuleKind::Regex => {
                push_entry(&mut fields, "domain_regex", &rule.value);
            }
        }
    }
    fields
}

fn push_entry(fields: &mut Map<String, Value>, key: &str, value: &str) {
    fields
        .entry(key.to_string())
        .or_insert_with(|| json!([]))
        .as_array_mut()
        .expect("match fields are arrays")
        .push(json!(value));
}

#[derive(Serialize)]
struct GeneratedConfig {
    log: LogConfig,
    dns: DnsConfig,
    inbounds: Vec<Inbound>,
    endpoints: Vec<Endpoint>,
    outbounds: Vec<Outbound>,
    route: RouteConfig,
}

#[derive(Serialize)]
struct LogConfig {
    level: &'static str,
    timestamp: bool,
}

#[derive(Serialize)]
struct DnsConfig {
    servers: Vec<Value>,
    rules: Vec<Value>,
    #[serde(rename = "final")]
    final_server: String,
}

#[derive(Serialize)]
struct Inbound {
    #[serde(rename = "type")]
    type_: &'static str,
    tag: &'static str,
    listen: &'static str,
    listen_port: u16,
}

#[derive(Serialize)]
#[serde(untagged)]
enum Endpoint {
    Wireguard(WireguardEndpoint),
    OpenVpn(Box<OpenVpnEndpoint>),
}

#[derive(Serialize)]
struct WireguardEndpoint {
    #[serde(rename = "type")]
    type_: &'static str,
    tag: &'static str,
    domain_resolver: &'static str,
    address: Vec<String>,
    private_key: String,
    peers: Vec<Peer>,
    #[serde(skip_serializing_if = "Option::is_none")]
    mtu: Option<u32>,
}

#[derive(Serialize)]
struct OpenVpnEndpoint {
    #[serde(rename = "type")]
    type_: &'static str,
    tag: &'static str,
    domain_resolver: &'static str,
    mode: &'static str,
    #[serde(flatten)]
    config: OpenVpnConfig,
    route_no_pull: bool,
}

#[derive(Serialize)]
struct Peer {
    address: String,
    port: u32,
    public_key: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pre_shared_key: Option<String>,
    allowed_ips: Vec<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    persistent_keepalive_interval: Option<u32>,
}

impl From<WireguardPeer> for Peer {
    fn from(peer: WireguardPeer) -> Self {
        Self {
            address: peer.host,
            port: peer.port,
            public_key: peer.public_key,
            pre_shared_key: peer.pre_shared_key,
            allowed_ips: peer.allowed_ips,
            persistent_keepalive_interval: peer.keepalive,
        }
    }
}

#[derive(Serialize)]
struct Outbound {
    #[serde(rename = "type")]
    type_: &'static str,
    tag: &'static str,
}

#[derive(Serialize)]
struct RouteConfig {
    rules: Vec<Value>,
    #[serde(rename = "final")]
    final_outbound: String,
    default_domain_resolver: &'static str,
}
