#[test]
fn maps_an_openvpn_profile_to_a_userspace_endpoint() {
    let generated = config_with(
        Protocol::OpenVpn,
        OPENVPN_PROFILE,
        OPENVPN_PROFILE_PATH,
        &base(),
    );
    let endpoint = &generated["endpoints"][0];
    assert_eq!(endpoint["type"], "openvpn-client");
    assert_eq!(endpoint["tag"], "tunnel");
    assert_eq!(endpoint["domain_resolver"], "dns-direct");
    assert_eq!(endpoint["mode"], "tls");
    assert_eq!(endpoint["network"], "udp");
    assert_eq!(endpoint["remote_random"], true);
    assert_eq!(
        endpoint["servers"],
        json!([
            { "server": "vpn.example.com", "server_port": 1194 },
            { "server": "backup.example.com", "server_port": 1195, "network": "tcp" },
        ])
    );
    assert_eq!(endpoint["username"], "alice");
    assert_eq!(endpoint["password"], "secret");
    assert_eq!(
        endpoint["tls"]["certificate"],
        "-----BEGIN CERTIFICATE-----\nFAKE_CA\n-----END CERTIFICATE-----"
    );
    assert_eq!(
        endpoint["tls"]["client_certificate"],
        "-----BEGIN CERTIFICATE-----\nFAKE_CERT\n-----END CERTIFICATE-----"
    );
    assert_eq!(
        endpoint["tls"]["client_key"],
        "-----BEGIN PRIVATE KEY-----\nFAKE_KEY\n-----END PRIVATE KEY-----"
    );
    assert_eq!(endpoint["tls"]["server_name"], "vpn.example.com");
    assert_eq!(endpoint["tls"]["server_name_type"], "name");
    assert_eq!(endpoint["tls"]["remote_certificate_tls"], "server");
    assert_eq!(
        endpoint["tls"]["control_wrap"],
        json!({
            "type": "tls_crypt",
            "key": "-----BEGIN OpenVPN Static key V1-----\nFAKE_TLS_CRYPT\n-----END OpenVPN Static key V1-----",
        })
    );
    assert_eq!(
        endpoint["data_ciphers"],
        json!(["AES-256-GCM", "AES-128-GCM"])
    );
    assert_eq!(endpoint["auth"], "SHA256");
    assert_eq!(endpoint["compression_lzo"], "no");
    assert_eq!(endpoint["mss_fix"], 1360);
    assert_eq!(endpoint["mtu"], 1400);
    assert_eq!(endpoint["ping_interval"], "10s");
    assert_eq!(endpoint["ping_restart"], "60s");
    assert_eq!(endpoint["route_no_pull"], true);
    assert_eq!(generated["dns"]["servers"][1]["server"], "10.8.0.1");
    assert_eq!(generated["route"]["final"], "direct");
}

#[test]
fn reads_openvpn_credentials_from_the_sidecar() {
    let dir = tempfile::tempdir().expect("tempdir");
    let profile = dir.path().join("work.ovpn");
    std::fs::write(
        &profile,
        "client\ndev tun\nremote vpn.example.com 1194\nauth-user-pass\n<ca>\nFAKE_CA\n</ca>\n",
    )
    .expect("profile");
    std::fs::write(dir.path().join("work.auth"), "alice\nsecret\n").expect("auth");

    let text = std::fs::read_to_string(&profile).expect("read");
    let generated = config_with(Protocol::OpenVpn, &text, &profile, &base());
    assert_eq!(generated["endpoints"][0]["username"], "alice");
    assert_eq!(generated["endpoints"][0]["password"], "secret");
}

#[test]
fn accepts_openvpn_peer_fingerprints_instead_of_a_ca() {
    let profile = "client\nremote vpn.example.com 1194\npeer-fingerprint AA:BB:CC\n";
    let generated = config_with(Protocol::OpenVpn, profile, OPENVPN_PROFILE_PATH, &base());
    assert_eq!(
        generated["endpoints"][0]["tls"]["peer_fingerprint"],
        json!(["aabbcc"])
    );
    assert!(generated["endpoints"][0]["tls"]["certificate"].is_null());
}

#[test]
fn rejects_openvpn_profiles_without_a_trust_anchor() {
    let error = generate_config(
        Protocol::OpenVpn,
        "client\nremote vpn.example.com 1194\n",
        Path::new(OPENVPN_PROFILE_PATH),
        &base(),
    )
    .expect_err("trust anchor");
    assert!(format!("{error:#}").contains("missing ca"));
}

#[test]
fn rejects_openvpn_tap_profiles() {
    let error = generate_config(
        Protocol::OpenVpn,
        "client\ndev tap0\nremote vpn.example.com 1194\n<ca>\nFAKE\n</ca>\n",
        Path::new(OPENVPN_PROFILE_PATH),
        &base(),
    )
    .expect_err("tap mode");
    assert!(format!("{error:#}").contains("TAP"));
}

#[test]
fn applies_tls_auth_key_directions() {
    let profile = "client\nremote vpn.example.com 1194\n<ca>\nFAKE\n</ca>\n<tls-auth>\nFAKE_KEY\n</tls-auth>\nkey-direction 1\n";
    let generated = config_with(Protocol::OpenVpn, profile, OPENVPN_PROFILE_PATH, &base());
    let wrap = &generated["endpoints"][0]["tls"]["control_wrap"];
    assert_eq!(wrap["type"], "tls_auth");
    assert_eq!(wrap["direction"], "client");
}
