use patchbay_core::config::Mode;
use patchbay_core::domains::{DomainRule, RuleKind};
use patchbay_core::engine::EngineOptions;
use patchbay_core::engine::singbox::generate_config;
use serde_json::{Value, json};

const SERVER_CONF: &str = r#"[Interface]
PrivateKey = FAKE_PRIVATE_KEY
Address = 10.0.0.2/32, fc00::2/128
DNS = 10.0.0.1, fc00::1
MTU = 1420

[Peer]
PublicKey = FAKE_PUBLIC_KEY
PresharedKey = FAKE_PRESHARED_KEY
AllowedIPs = 0.0.0.0/0, ::/0
Endpoint = vpn.example.com:51820
PersistentKeepalive = 25
"#;

const MERGED_SERVER_CONF: &str = r#"[Interface]
PrivateKey = FAKE_PRIVATE_KEY
Address = 10.0.0.2/32
Address = 10.0.0.3/32, fc00::2/128
DNS = 10.0.0.1
DNS = 10.0.0.9

[Peer]
PublicKey = FAKE_PUBLIC_KEY
AllowedIPs = 0.0.0.0/0
Endpoint = vpn.example.com:51820
"#;

const HEADER: &str = "// auto-generated by patchbay; edits will be overwritten\n";

fn rule(id: &str, value: &str, kind: RuleKind, enabled: bool) -> DomainRule {
    DomainRule {
        id: id.into(),
        value: value.into(),
        kind,
        enabled,
    }
}

fn base() -> EngineOptions {
    EngineOptions {
        socks_port: 25344,
        mode: Mode::Split,
        domains: vec![
            rule("a", "reddit.com", RuleKind::Domain, true),
            rule("b", "medium.com", RuleKind::Domain, false),
        ],
    }
}

fn full_options() -> EngineOptions {
    EngineOptions {
        socks_port: 1080,
        mode: Mode::Full,
        domains: vec![
            rule("r", "^.*\\.example\\.com$", RuleKind::Regex, true),
            rule("d", "reddit.com", RuleKind::Domain, true),
        ],
    }
}

fn config_for(conf: &str, options: &EngineOptions) -> Value {
    let raw = generate_config(conf, options).expect("config");
    let body = raw.strip_prefix(HEADER).expect("generated header");
    serde_json::from_str(body).expect("json")
}

fn config(options: &EngineOptions) -> Value {
    config_for(SERVER_CONF, options)
}

#[test]
fn marks_the_generated_config_as_auto_generated() {
    let raw = generate_config(SERVER_CONF, &base()).expect("config");
    assert!(raw.starts_with("// auto-generated by patchbay"));
}

#[test]
fn maps_the_wireguard_conf_to_a_userspace_endpoint() {
    let generated = config(&base());
    let endpoint = &generated["endpoints"][0];
    assert_eq!(endpoint["type"], "wireguard");
    assert_eq!(endpoint["tag"], "tunnel");
    assert_eq!(endpoint["address"], json!(["10.0.0.2/32", "fc00::2/128"]));
    assert_eq!(endpoint["private_key"], "FAKE_PRIVATE_KEY");
    assert_eq!(endpoint["mtu"], json!(1420));
    assert_eq!(endpoint["domain_resolver"], "dns-direct");
    assert_eq!(
        endpoint["peers"][0],
        json!({
            "address": "vpn.example.com",
            "port": 51820,
            "public_key": "FAKE_PUBLIC_KEY",
            "pre_shared_key": "FAKE_PRESHARED_KEY",
            "allowed_ips": ["0.0.0.0/0", "::/0"],
            "persistent_keepalive_interval": 25,
        })
    );
}

#[test]
fn listens_on_the_configured_socks_port() {
    let generated = config(&base());
    assert_eq!(
        generated["inbounds"][0],
        json!({
            "type": "socks",
            "tag": "socks-in",
            "listen": "127.0.0.1",
            "listen_port": 25344,
        })
    );
}

#[test]
fn routes_enabled_domains_through_the_tunnel_and_skips_disabled_ones() {
    let generated = config(&base());
    assert_eq!(
        generated["route"]["rules"],
        json!([{
            "domain": ["reddit.com"],
            "domain_suffix": [".reddit.com"],
            "action": "route",
            "outbound": "tunnel",
        }])
    );
    assert_eq!(generated["route"]["final"], "direct");
}

#[test]
fn keeps_regex_rules_as_domain_regex() {
    let options = EngineOptions {
        domains: vec![rule("r", "^.*\\.example\\.com$", RuleKind::Regex, true)],
        ..base()
    };
    let generated = config(&options);
    assert_eq!(
        generated["route"]["rules"][0]["domain_regex"],
        json!(["^.*\\.example\\.com$"])
    );
}

#[test]
fn resolves_tunneled_domains_through_the_tunnel_dns() {
    let generated = config(&base());
    let servers = generated["dns"]["servers"].as_array().expect("servers");
    assert!(servers.contains(&json!({
        "type": "udp",
        "tag": "dns-tunnel",
        "server": "10.0.0.1",
        "detour": "tunnel",
    })));
    assert_eq!(
        generated["dns"]["rules"],
        json!([
            { "domain": ["reddit.com"], "domain_suffix": [".reddit.com"], "server": "dns-tunnel" }
        ])
    );
    assert_eq!(generated["dns"]["final"], "dns-direct");
    assert_eq!(generated["route"]["default_domain_resolver"], "dns-direct");
}

#[test]
fn empty_split_rules_tunnel_nothing() {
    let options = EngineOptions {
        domains: vec![],
        ..base()
    };
    let generated = config(&options);
    assert_eq!(generated["route"]["rules"], json!([]));
    assert_eq!(generated["route"]["final"], "direct");
}

#[test]
fn full_mode_sends_everything_through_the_tunnel() {
    let options = EngineOptions {
        mode: Mode::Full,
        ..base()
    };
    let generated = config(&options);
    assert_eq!(generated["route"]["rules"], json!([]));
    assert_eq!(generated["route"]["final"], "tunnel");
    assert_eq!(generated["route"]["default_domain_resolver"], "dns-direct");
    assert_eq!(generated["dns"]["rules"], json!([]));
    assert_eq!(generated["dns"]["final"], "dns-tunnel");
    assert_eq!(generated["endpoints"][0]["domain_resolver"], "dns-direct");
}

#[test]
fn merges_repeated_address_and_dns_lines() {
    let generated = config_for(MERGED_SERVER_CONF, &base());
    assert_eq!(
        generated["endpoints"][0]["address"],
        json!(["10.0.0.2/32", "10.0.0.3/32", "fc00::2/128"])
    );
    assert_eq!(generated["dns"]["servers"][1]["server"], "10.0.0.1");
}

#[test]
fn rejects_a_config_without_interface_or_peer_fields() {
    assert!(generate_config("[Interface]\nPrivateKey = x\n", &base()).is_err());
}

#[test]
fn split_output_matches_typescript() {
    let generated = generate_config(SERVER_CONF, &base()).expect("config");
    assert_eq!(generated, include_str!("fixtures/split.generated.json"));
}

#[test]
fn full_output_matches_typescript() {
    let generated = generate_config(MERGED_SERVER_CONF, &full_options()).expect("config");
    assert_eq!(generated, include_str!("fixtures/full.generated.json"));
}
